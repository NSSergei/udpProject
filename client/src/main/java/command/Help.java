package command;

public class Help implements Command {
    @Override
    public void execute() {
        System.out.println(
                """
                        Доступным команды:
                 
                        help : вывести справку по доступным командам.
                        
                        info : вывести в стандартный поток вывода информацию о коллекции (тип, дата
                                инициализации, количество элементов и т.д.).
                                
                        show : вывести в стандартный поток вывода все элементы коллекции в строковом
                                представлении.
                                
                        add {element} : добавить новый элемент в коллекцию.
                        
                        update id {element} : обновить значение элемента коллекции, id которого равен заданному значению 
                                element.
                                
                        remove_by_id id : удалить элемент из коллекции по его id.
                                
                        clear : очистить коллекцию.
                                
                        save : сохранить коллекцию в файл.
                                
                        execute_script file_name : считать и исполнить скрипт из указанного файла. В скрипте
                                содержатся команды в таком же виде, в котором их вводит пользователь в интерактивном
                                режиме.
                                
                        exit : завершить программу (без сохранения в файл).
                        
                        remove_first : удалить первый элемент из коллекции.
                        
                        head : вывести первый элемент коллекции.
                        
                        remove_greater {element} : удалить из коллекции все элементы, превышающие заданный.
                        
                        average_of_average_mark : вывести среднее значение поля averageMark для всех элементов
                                коллекции.
                        
                        filter_contains_name name : вывести элементы, значение поля name которых содержит
                                заданную подстроку .
                """
        );
    }
}
